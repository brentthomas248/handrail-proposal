import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const tile = 512;
const destination = new URL('../public/paper-grain.svg', import.meta.url);
const manifestPath = new URL(
  '../agentic-ui/assets.manifest.json',
  import.meta.url,
);
let seed = 0x50415045;
const random = () => {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 2 ** 32;
};
const number = (value) => Number(value.toFixed(2));
const groups = [[], [], [], []];

for (let index = 0; index < 520; index += 1) {
  const x = random() * tile;
  const y = random() * tile;
  const angle = random() * Math.PI * 2;
  const length = 3 + random() ** 1.4 * 10;
  const dx = Math.cos(angle) * length;
  const dy = Math.sin(angle) * length;
  const bow = (random() - 0.5) * 1.9;
  const path = `M${number(x)} ${number(y)}q${number(dx * 0.47 - Math.sin(angle) * bow)} ${number(dy * 0.47 + Math.cos(angle) * bow)} ${number(dx)} ${number(dy)}`;
  const group = index % groups.length;
  const copiesX = [0];
  const copiesY = [0];
  if (Math.min(x, x + dx) < 2) copiesX.push(tile);
  if (Math.max(x, x + dx) > tile - 2) copiesX.push(-tile);
  if (Math.min(y, y + dy) < 2) copiesY.push(tile);
  if (Math.max(y, y + dy) > tile - 2) copiesY.push(-tile);
  for (const offsetX of copiesX)
    for (const offsetY of copiesY)
      groups[group].push(
        `<path d="${path}"${offsetX || offsetY ? ` transform="translate(${offsetX} ${offsetY})"` : ''}/>`,
      );
}

const pores = [];
for (let index = 0; index < 1250; index += 1) {
  const x = number(random() * tile);
  const y = number(random() * tile);
  const radius = number(0.22 + random() * 0.5);
  pores.push(`<circle cx="${x}" cy="${y}" r="${radius}"/>`);
}

// Periodic copies make the low-frequency formation continuous at tile edges.
const formation = [
  [48, 90, 140, 68, 'shade'],
  [375, 24, 158, 92, 'shade'],
  [248, 342, 154, 82, 'shade'],
  [487, 456, 128, 67, 'shade'],
  [161, 217, 139, 91, 'light'],
  [441, 279, 150, 114, 'light'],
].flatMap(([x, y, rx, ry, paint]) => {
  const copies = [];
  for (const offsetX of [-tile, 0, tile])
    for (const offsetY of [-tile, 0, tile])
      if (
        x + offsetX + rx > 0 &&
        x + offsetX - rx < tile &&
        y + offsetY + ry > 0 &&
        y + offsetY - ry < tile
      )
        copies.push(
          `<ellipse cx="${x + offsetX}" cy="${y + offsetY}" rx="${rx}" ry="${ry}" fill="url(#${paint})"/>`,
        );
  return copies;
});

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${tile}" height="${tile}" viewBox="0 0 ${tile} ${tile}">
  <desc>Deterministic matte paper: irregular fibers, fine pores and continuous low-contrast formation. Generated by scripts/generate-paper-grain.mjs; no runtime filters.</desc>
  <defs>
    <radialGradient id="shade"><stop stop-color="#6a543d" stop-opacity=".015"/><stop offset="1" stop-color="#6a543d" stop-opacity="0"/></radialGradient>
    <radialGradient id="light"><stop stop-color="#fffdf7" stop-opacity=".02"/><stop offset="1" stop-color="#fffdf7" stop-opacity="0"/></radialGradient>
  </defs>
  ${formation.join('\n  ')}
  <g fill="#6b553f" opacity=".085">${pores.join('')}</g>
  <g fill="none" stroke="#70573e" stroke-width=".85" stroke-linecap="round" opacity=".13">${groups[0].join('')}</g>
  <g fill="none" stroke="#887057" stroke-width="1.15" stroke-linecap="round" opacity=".16">${groups[1].join('')}</g>
  <g fill="none" stroke="#fffef9" stroke-width="1.35" stroke-linecap="round" opacity=".16">${groups[2].join('')}</g>
  <g fill="none" stroke="#80674c" stroke-width=".65" stroke-linecap="round" opacity=".18">${groups[3].join('')}</g>
</svg>
`;

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
const asset = manifest.assets.find((entry) => entry.id === 'paper-grain');
if (!asset)
  throw new Error('Paper texture is missing from the asset manifest.');
const identity = {
  sha256: createHash('sha256').update(svg).digest('hex'),
  width: tile,
  height: tile,
  generator: 'scripts/generate-paper-grain.mjs',
};

if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== svg)
    throw new Error('Paper texture differs from its deterministic source.');
  for (const [key, value] of Object.entries(identity))
    if (asset[key] !== value)
      throw new Error(`Paper texture manifest has a stale ${key}.`);
  console.log('Paper texture and manifest match their deterministic source.');
} else {
  await writeFile(destination, svg);
  Object.assign(asset, identity);
  manifest.generatedAt = new Date().toISOString();
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(
    `Generated ${Buffer.byteLength(svg)} bytes of static paper texture.`,
  );
}
